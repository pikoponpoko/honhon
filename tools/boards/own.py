def img(x, y, w, h, g=None):
    o = {'t': 'i', 'b': [x, y, w, h]}
    if g: o['g'] = g
    return o

def txt(x, y, w, h, s, z, c=INK, wt=None, al=None, an=None, ld=120, ps=None):
    o = {'t': 'x', 'b': [x, y, w, h], 's': s, 'z': z, 'c': c, 'f': F, 'ld': ld}
    if wt: o['wt'] = wt
    if al: o['al'] = al
    if an: o['an'] = an
    if ps: o['ps'] = ps
    return o

def para(*qs):
    """段落ごとの (倍率, 太字, 色の役割)"""
    out = []
    for q in qs:
        r, b = q[0], q[1]
        d = {'r': r, 'b': b}
        if len(q) > 2: d['cr'] = q[2]
        out.append(d)
    return out

def chara(main, subs, title_b, desc_b, role, name, name_z, extra=()):
    """キャラクター紹介：左上に大きな絵、右に表情・ポーズ、下に役割＋名前と説明"""
